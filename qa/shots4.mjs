import puppeteer from 'puppeteer-core';
const BASE = 'http://localhost:4000';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const browser = await puppeteer.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: 'new', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage();
await page.setViewport({ width: 1366, height: 768 });
await fetch(BASE + '/api/settings', { method: 'PATCH', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ theme: 'light', skyMode: 'on' }) });
await fetch(BASE + '/api/page', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ page: 1 }) });
await page.goto(BASE + '/', { waitUntil: 'domcontentloaded' });
await sleep(1500);
await page.evaluate(() => showAlarm({ kind: 'alarm', time: '09:41', label: 'QA solid alarm' }));
await sleep(2200);
await page.screenshot({ path: 'qa/shots/r4-3-alarm-solid.png' });
await page.keyboard.press(' ');
await sleep(800);
await fetch(BASE + '/api/alert', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ kind: 'battery' }) });
await sleep(2200);
await page.screenshot({ path: 'qa/shots/r4-5-alert-solid.png' });
await page.keyboard.press(' ');
await sleep(800);
await page.keyboard.press('6');
await sleep(700);
await page.evaluate(() => { const el = document.querySelector('#set-volume'); el.closest('.set-card').scrollIntoView({ block: 'center' }); });
await sleep(500);
await page.screenshot({ path: 'qa/shots/r4-2-settings.png' });
const remote = await browser.newPage();
await remote.setViewport({ width: 390, height: 844 });
await remote.goto(BASE + '/remote', { waitUntil: 'domcontentloaded' });
await sleep(1500);
await remote.screenshot({ path: 'qa/shots/r4-4-remote-settings.png', fullPage: true });
await browser.close();
